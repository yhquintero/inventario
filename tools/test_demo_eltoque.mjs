#!/usr/bin/env node
import assert from "node:assert/strict";
import { cpSync, mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const tmp = mkdtempSync(join(tmpdir(), "ng-demo-"));
cpSync(join(root, "web/js"), tmp, { recursive: true });
writeFileSync(join(tmp, "package.json"), '{"type":"module"}');
globalThis.localStorage = { getItem: () => null, setItem: () => {}, removeItem: () => {} };
const { store } = await import(pathToFileURL(join(tmp, "store.js")).href);
store.state.session = { role: "ADMINISTRADOR", displayName: "Prueba" };
store.seed();
// Sin municipios creados no se permite llenar datos de prueba.
assert.match(store.populateDemoWarehouses().error, /Primero debes crear los municipios/);
// Crear Pinar del Río (11 municipios en 0) para probar el llenado sobre esos almacenes.
assert.equal(store.ensureMunicipalWarehouses("restaurar", "Pinar del Río").created.length, 11);
const principal = store.defaultWarehouse();
const wh = store.existingMunicipalWarehouses("Pinar del Río")[0];
const product = store.activeProducts()[0];
store.setStockIn(product, wh.id, 12);
const before = store.stockIn(product, principal.id);
const oldPrices = store.activeProducts().map((p) => p.precioVentaUsd);
const r = store.populateDemoWarehouses();
assert.ok(r.changed > 1000 && r.warehouses === 11);
assert.equal(store.stockIn(product, wh.id), 12);
assert.equal(store.stockIn(product, principal.id), before);
assert.deepEqual(store.activeProducts().map((p) => p.precioVentaUsd), oldPrices);
assert.ok(store.state.warehouseEntries.filter((e) => e.source === "DEMOSTRACIÓN").length === 11);
assert.equal(store.populateDemoWarehouses().changed, 0);
const entry = store.state.warehouseEntries.find((e) => e.source === "DEMOSTRACIÓN" && e.warehouseId === wh.id);
const demoItem = entry.items.find((i) => i.field === "stock");
assert.ok(store.stockIn(store.state.products.find((p) => p.id === demoItem.productId), wh.id) > 0);
const demoProduct = store.state.products.find((p) => p.id === demoItem.productId);
store.setStockIn(demoProduct, wh.id, demoItem.new + 1);
assert.ok(store.undoWarehouseEntry(entry.id).error, "no se revierte una existencia que cambió después");
store.setStockIn(demoProduct, wh.id, demoItem.new);
store.state.movements.push({ id: "demo-movement", productId: demoProduct.id, warehouseId: wh.id });
assert.ok(store.undoWarehouseEntry(entry.id).error, "no se revierten datos con movimientos posteriores");
store.state.movements.pop();
assert.ok(store.undoWarehouseEntry(entry.id).ok);
assert.equal(store.stockIn(store.state.products.find((p) => p.id === demoItem.productId), wh.id), 0);
assert.equal(store.stockIn(product, wh.id), 12);
store.state.session.role = "ECONOMICO";
assert.ok(store.populateDemoWarehouses().error);
const data = { date: "2026-11-08", publishedAt: "2026-11-08T18:17:00+00:00", source: "https://eltoque.com/tasas-de-cambio-cuba", rates: { USD:930, EUR:1020, MLC:726.72, CAD:598.81, MXN:51.43, ZELLE:898.89, CLA:828.91 } };
const oldCount = store.state.rates.length;
assert.ok(store.importEltoqueRates({ ...data, rates: { USD: 900 } }).error);
assert.equal(store.state.rates.length, oldCount);
assert.equal(store.importEltoqueRates(data).count, 7);
for (const [currency, rate] of Object.entries(data.rates)) {
  const record = store.state.rates.find((r) => r.currency === currency && r.date === data.date);
  assert.equal(record.rate, rate);
  assert.ok(record.note.includes("elTOQUE"));
}
const count = store.state.rates.length;
store.importEltoqueRates(data);
assert.equal(store.state.rates.length, count);
store.state.session.role = "ALMACENERO";
assert.ok(store.importEltoqueRates(data).error);
console.log("✔ Demostración por almacén (tras crear municipios) y siete tasas, permisos e idempotencia");
